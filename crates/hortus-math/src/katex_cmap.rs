    fn assert_font_cmap(name: &str, data: &[u8]) {
        let face = ttf_parser::Face::parse(data, 0).unwrap();
        let mut actual = BTreeSet::new();
        for subtable in face.tables().cmap.unwrap().subtables {
            subtable.codepoints(|codepoint| {
                if char::from_u32(codepoint)
                    .and_then(|character| face.glyph_index(character))
                    .is_some_and(|glyph| glyph.0 != 0)
                {
                    actual.insert(codepoint);
                }
            });
        }
        let expected: BTreeSet<_> = ranges(name)
            .unwrap()
            .iter()
            .flat_map(|(start, end)| *start..=*end)
            .collect();
        assert_eq!(actual, expected, "{name}");
        assert!(!contains(name, 0xffff));
    }
