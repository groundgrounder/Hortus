//! 零外部依赖中英双语本地化模块：按 `LC_ALL` → `LC_MESSAGES` → `LANG` → `LANGUAGE`
//! 自动匹配 `zh-Hans` 与源语言 `en`，统一落实 `D-2026-11-24-10` 克制文案规范。

use std::sync::OnceLock;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    ZhHans,
}

static CURRENT_LANG: OnceLock<Lang> = OnceLock::new();

/// 按 POSIX 环境变量优先级解析界面语言：`zh*` → `ZhHans`，其余默认 `En`。
pub fn detect_lang_from_vars(
    lc_all: Option<&str>,
    lc_messages: Option<&str>,
    lang: Option<&str>,
    language: Option<&str>,
) -> Lang {
    for raw in [lc_all, lc_messages, lang].into_iter().flatten() {
        let trimmed = raw.trim();
        if !trimmed.is_empty() {
            return parse_locale_tag(trimmed);
        }
    }
    if let Some(raw) = language {
        for part in raw.split(':') {
            let trimmed = part.trim();
            if !trimmed.is_empty() {
                return parse_locale_tag(trimmed);
            }
        }
    }
    Lang::En
}

fn parse_locale_tag(tag: &str) -> Lang {
    let lower = tag.trim().to_ascii_lowercase();
    if lower == "zh"
        || lower.starts_with("zh_")
        || lower.starts_with("zh-")
        || lower.starts_with("zh.")
    {
        Lang::ZhHans
    } else {
        Lang::En
    }
}

pub fn current_lang() -> Lang {
    *CURRENT_LANG.get_or_init(|| {
        detect_lang_from_vars(
            std::env::var("LC_ALL").ok().as_deref(),
            std::env::var("LC_MESSAGES").ok().as_deref(),
            std::env::var("LANG").ok().as_deref(),
            std::env::var("LANGUAGE").ok().as_deref(),
        )
    })
}

pub fn tr(key: Key) -> &'static str {
    tr_for(current_lang(), key)
}

pub fn tr_for(lang: Lang, key: Key) -> &'static str {
    let (en, zh) = pair(key);
    match lang {
        Lang::En => en,
        Lang::ZhHans => zh,
    }
}

pub fn fmt1(key: Key, a0: impl std::fmt::Display) -> String {
    fmt1_for(current_lang(), key, a0)
}

pub fn fmt1_for(lang: Lang, key: Key, a0: impl std::fmt::Display) -> String {
    tr_for(lang, key).replace("{0}", &a0.to_string())
}

pub fn fmt2(key: Key, a0: impl std::fmt::Display, a1: impl std::fmt::Display) -> String {
    fmt2_for(current_lang(), key, a0, a1)
}

pub fn fmt2_for(
    lang: Lang,
    key: Key,
    a0: impl std::fmt::Display,
    a1: impl std::fmt::Display,
) -> String {
    tr_for(lang, key)
        .replace("{0}", &a0.to_string())
        .replace("{1}", &a1.to_string())
}

pub fn fmt3(
    key: Key,
    a0: impl std::fmt::Display,
    a1: impl std::fmt::Display,
    a2: impl std::fmt::Display,
) -> String {
    fmt3_for(current_lang(), key, a0, a1, a2)
}

pub fn fmt3_for(
    lang: Lang,
    key: Key,
    a0: impl std::fmt::Display,
    a1: impl std::fmt::Display,
    a2: impl std::fmt::Display,
) -> String {
    tr_for(lang, key)
        .replace("{0}", &a0.to_string())
        .replace("{1}", &a1.to_string())
        .replace("{2}", &a2.to_string())
}

pub fn fmt4(
    key: Key,
    a0: impl std::fmt::Display,
    a1: impl std::fmt::Display,
    a2: impl std::fmt::Display,
    a3: impl std::fmt::Display,
) -> String {
    tr_for(current_lang(), key)
        .replace("{0}", &a0.to_string())
        .replace("{1}", &a1.to_string())
        .replace("{2}", &a2.to_string())
        .replace("{3}", &a3.to_string())
}

pub fn fmt5(
    key: Key,
    a0: impl std::fmt::Display,
    a1: impl std::fmt::Display,
    a2: impl std::fmt::Display,
    a3: impl std::fmt::Display,
    a4: impl std::fmt::Display,
) -> String {
    tr_for(current_lang(), key)
        .replace("{0}", &a0.to_string())
        .replace("{1}", &a1.to_string())
        .replace("{2}", &a2.to_string())
        .replace("{3}", &a3.to_string())
        .replace("{4}", &a4.to_string())
}

