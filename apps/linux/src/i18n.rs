    #[test]
    fn all_translation_keys_are_complete_and_follow_copy_rules() {
        let forbidden = [
            "知识库",
            "笔记库",
            "智能体",
            "VTE4",
            "diff",
            "hunk",
            "argv",
            "shell 拆分",
            "shell splitting",
            "接入",
            "歧义",
            "知识导航",
            "Vault",
            "vault",
        ];
        for &key in ALL_KEYS {
            let en = tr_for(Lang::En, key);
            let zh = tr_for(Lang::ZhHans, key);
            assert!(!en.trim().is_empty(), "empty en for {key:?}");
            assert!(!zh.trim().is_empty(), "empty zh for {key:?}");

            for idx in 0..5 {
                let ph = format!("{{{idx}}}");
                assert_eq!(
                    en.contains(&ph),
                    zh.contains(&ph),
                    "placeholder {ph} mismatch for {key:?}: en={en:?}, zh={zh:?}"
                );
            }

            if matches!(key, Key::CliUsageProd) {
                // CLI --vault 参数名允许保留，但其余说明文本不得违反词表。
                let en_clean = en.replace("--vault", "");
                let zh_clean = zh.replace("--vault", "");
                for word in forbidden {
                    assert!(
                        !en_clean.contains(word),
                        "forbidden {word:?} in en {key:?}: {en}"
                    );
                    assert!(
                        !zh_clean.contains(word),
                        "forbidden {word:?} in zh {key:?}: {zh}"
                    );
                }
                continue;
            }
            #[cfg(feature = "automation")]
            if matches!(key, Key::CliUsageAutoSuffix) {
                let en_clean = en.replace("--terminal-agent-vault2", "");
                let zh_clean = zh.replace("--terminal-agent-vault2", "");
                for word in forbidden {
                    assert!(
                        !en_clean.contains(word),
                        "forbidden {word:?} in en {key:?}: {en}"
                    );
                    assert!(
                        !zh_clean.contains(word),
                        "forbidden {word:?} in zh {key:?}: {zh}"
                    );
                }
                continue;
            }

            for word in forbidden {
                if word == "vault" && matches!(key, Key::CliMissingVaultArg) {
                    continue;
                }
                assert!(!en.contains(word), "forbidden {word:?} in en {key:?}: {en}");
                assert!(!zh.contains(word), "forbidden {word:?} in zh {key:?}: {zh}");
            }
        }
    }
